// Landmarks recorded by running the app's hand tracker (MediaPipe HandLandmarker in the Electron
// renderer) on the photos in tests/e2e/fixtures/hands, each shown letterboxed in a 1280×720
// un-mirrored camera frame. They let the unit tests check the gesture constants against real
// hands. `actualSide` is the person's real hand as determined by looking at the photo (see the
// README next to the photos); `label` is what the tracker reported.
import type { HandSide } from '@shared/controls';
import type { Landmark, RawHand } from '../types';

export const RECORDED_IMAGE_ASPECT = 1280 / 720;

export interface RecordedHand {
  photo: string;
  shows: string;
  actualSide: HandSide;
  hand: RawHand;
}

function toLandmarks(flat: readonly number[]): Landmark[] {
  const landmarks: Landmark[] = [];
  for (let index = 0; index + 2 < flat.length; index += 3) {
    landmarks.push({ x: flat[index] ?? 0, y: flat[index + 1] ?? 0, z: flat[index + 2] ?? 0 });
  }
  return landmarks;
}

/** `image` and `world` are the 21 landmarks flattened to x, y, z, x, y, z, … */
function recorded(
  photo: string,
  shows: string,
  actualSide: HandSide,
  label: RawHand['label'],
  score: number,
  image: readonly number[],
  world: readonly number[],
): RecordedHand {
  return {
    photo,
    shows,
    actualSide,
    hand: { label, score, landmarks: toLandmarks(image), worldLandmarks: toLandmarks(world) },
  };
}

